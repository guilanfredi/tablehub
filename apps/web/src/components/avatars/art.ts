/**
 * Avatares low poly: cabeças de animais feitas de polígonos chapados (2–4 tons por face),
 * em `viewBox="0 0 100 100"` sobre um fundo circular. Arte própria.
 */
export type Poly = [points: string, fill: string];
export interface AvatarArt {
  bg: string;
  polys: Poly[];
}

type Tones = [light: string, base: string, shade: string, dark: string];

const pts = (xy: number[]) => {
  const out: string[] = [];
  for (let i = 0; i < xy.length; i += 2) out.push(`${xy[i]},${xy[i + 1]}`);
  return out.join(' ');
};
/** Polígono a partir de pares x,y. */
const p = (fill: string, ...xy: number[]): Poly => [pts(xy), fill];
/** Polígono e o seu espelho em relação ao centro (x → 100 − x). */
const m = (fill: string, ...xy: number[]): Poly[] => [p(fill, ...xy), p(fill, ...xy.map((v, i) => (i % 2 === 0 ? 100 - v : v)))];
/** Losango centrado em (x, y). */
const dia = (fill: string, x: number, y: number, r: number): Poly => p(fill, x, y - r, x + r * 0.8, y, x, y + r, x - r * 0.8, y);
/** Par de olhos (losangos) simétricos em relação a `cx`. */
const eyes = (y: number, dx: number, r = 3.5, fill = '#1d1b1a', cx = 50): Poly[] => [dia(fill, cx - dx, y, r), dia(fill, cx + dx, y, r)];

/** Cabeça facetada: octógono irregular dividido em triângulos a partir de um ponto central. */
function head(t: Tones, { cx = 50, w = 30, top = 24, mid = 52, bottom = 80 } = {}): Poly[] {
  const [light, base, shade, dark] = t;
  const T = [cx, top];
  const UL = [cx - w * 0.72, top + (mid - top) * 0.35];
  const L = [cx - w, mid];
  const BL = [cx - w * 0.62, bottom - (bottom - mid) * 0.2];
  const B = [cx, bottom];
  const BR = [cx + w * 0.62, BL[1]];
  const R = [cx + w, mid];
  const UR = [cx + w * 0.72, UL[1]];
  const C = [cx - w * 0.08, mid - (mid - top) * 0.12];
  const tri = (fill: string, a: number[], b: number[]) => p(fill, ...C, ...a, ...b);
  return [
    tri(light, T, UL),
    tri(base, UL, L),
    tri(shade, L, BL),
    tri(base, BL, B),
    tri(base, T, UR),
    tri(shade, UR, R),
    tri(dark, R, BR),
    tri(shade, BR, B),
  ];
}

